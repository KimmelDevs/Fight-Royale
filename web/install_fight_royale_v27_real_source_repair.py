def decode_patches() -> dict[str, dict[str, list[list[str]]]]:
    data = "".join(_PATCH_B85)
    return json.loads(zlib.decompress(base64.b85decode(data.encode("ascii"))))


def read_source(path: Path) -> tuple[str, bytes, str]:
    raw = path.read_bytes()
    bom = b"\xef\xbb\xbf" if raw.startswith(b"\xef\xbb\xbf") else b""
    contents = raw[len(bom):].decode("utf-8")
    newline = "\r\n" if contents.count("\r\n") > contents.count("\n") / 2 else "\n"
    return contents.replace("\r\n", "\n"), bom, newline


def build_bytes(text: str, bom: bytes, newline: str) -> bytes:
    return bom + text.replace("\n", newline).encode("utf-8")


def install(base: Path, *, dry_run: bool) -> int:
    base = base.expanduser().resolve()
    if base.name.lower() == "src" and (base / "game" / "fighter.ts").is_file():
        base = base.parent
    print(f"FIGHT ROYALE V27 — REAL SOURCE REPAIR | target: {base}")
    marker = base / "src" / "game" / "model.ts"
    if not marker.is_file():
        raise RuntimeError("Missing src/game/model.ts. Run from fight-royale/web or supply the web folder.")
    source_model = read_source(marker)[0]
    if "ZEPHYR_V26_COMBO_ANTICLIP" in source_model:
        print("V26/V27 gameplay and animation changes are already present. No files changed.")
        return 0
    if "ZEPHYR_DRAGON_DANCER_V1" not in source_model or "ZEPHYR_BODY_GRIP_V21" not in source_model:
        raise RuntimeError("Expected Zephyr V21+ with detached three-section staff. No files changed.")
    if "ZEPHYR_MODE_BALANCE_V25" in source_model:
        variant = "v25"
    elif "ZEPHYR_TRISTAFF_PROPORTIONS_V24" in source_model:
        variant = "v24"
    else:
        variant = "v23"
    patches = decode_patches()[variant]
    updates: dict[str, bytes] = {}
    orig: dict[str, bytes] = {}
    print(f"  recognized starting point: {variant.upper()}")
    # All patches are validated against in-memory text first.
    for rel, hunks in patches.items():
        dest = base / rel
        if not dest.is_file():
            raise RuntimeError(f"Missing {rel}. No files changed.")
        old_text, bom, eol = read_source(dest)
        new_text = old_text
        for idx, (old, new) in enumerate(hunks, 1):
            n = new_text.count(old)
            if n != 1:
                raise RuntimeError(
                    f"{rel}: patch block {idx}/{len(hunks)} expected once, found {n}. "
                    "Your local source differs from the uploaded src ZIP. "
                    "No files changed; upload your latest src ZIP again."
                )
            new_text = new_text.replace(old, new, 1)
        if old_text != new_text:
            updates[rel] = build_bytes(new_text, bom, eol)
            orig[rel] = dest.read_bytes()
    # Verify integration markers after all replacements. No files written yet.
    def prepared_text(rel: str) -> str:
        return updates[rel].decode("utf-8-sig").replace("\r\n", "\n") if rel in updates else read_source(base/rel)[0]
    checks = {
        "src/game/model.ts": ("ZEPHYR_TRISTAFF_PROPORTIONS_V24", "ZEPHYR_V26_COMBO_ANTICLIP"),
        "src/game/fighter.ts": ("ZEPHYR_FULL_BALANCE_RHYTHM_V25", "GUARD_FATIGUE_V26", "NYTHERA_V26_TUNING"),
        "src/game/ai.ts": ("GUARD_FATIGUE_V26", "ZEPHYR_MODE_BALANCE_V25"),
        "src/game/vrm.ts": ("ZEPHYR_COMBO_BODY_V26",),
        "src/game/game.ts": ("GUARD_FATIGUE_V26", "ZEPHYR_MODE_HUD_SYNC_V25"),
    }
    for rel, required in checks.items():
        txt = prepared_text(rel)
        for needle in required:
            if needle not in txt:
                raise RuntimeError(f"Integration check failed: {rel} missing {needle!r}. No files changed.")
    if not updates:
        print("Everything is already installed; no changes.")
        return 0
    print(f"  validated {len(updates)} file(s), with exact and unique source anchors")
    for rel in updates:
        print("   +", rel)
    if dry_run:
        print("DRY RUN: no files were changed.")
        return 0
    stamp = dt.datetime.now().strftime("v27-%Y%m%d-%H%M%S-%f")
    backup_dir = base / ".zephyr-backups" / stamp
    # Backups first. Replacing only changed files, never clobbering unrelated paths.
    for rel in updates:
        out = backup_dir / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(orig[rel])
    changed = []
    try:
        for rel, content in updates.items():
            target = base / rel
            fd, temp_name = tempfile.mkstemp(prefix=".fight-v27-", suffix=".tmp", dir=target.parent)
            try:
                with os.fdopen(fd, "wb") as fh:
                    fh.write(content)
                    fh.flush()
                    os.fsync(fh.fileno())
                os.replace(temp_name, target)
            finally:
                if os.path.exists(temp_name):
                    os.unlink(temp_name)
            changed.append(rel)
    except Exception:
        for rel in reversed(changed):
            (base / rel).write_bytes(orig[rel])
        raise
    print("\nInstalled the combined V24/V25/V26 changes successfully.")
    print("  Zephyr: smaller weapon; mode balance; +20% HP and 20% damage reduction;")
    print("          25s Rhythm; +0.20x speed per stack; V26 grip/body cleanup.")
    print("  Nythera: 3 aerial light slices, Dreadfall cap 1.48x.")
    print("  Everyone: Guard Fatigue -0.02x/defended hit, 1 stack decays every 3s.")
    print("  AI: mode-aware Zephyr and guard-fatigue awareness for the roster.")
    print("  Backups:", backup_dir)
    print("Next: npx tsc --noEmit -p . && npm run dev")
    return 0


def main() -> int:
    args = sys.argv[1:]
    dry = "--dry-run" in args
    targets = [arg for arg in args if arg != "--dry-run"]
    if len(targets) > 1:
        print("Usage: python install_fight_royale_v27_real_source_repair.py [web-folder] [--dry-run]", file=sys.stderr)
        return 2
    base = Path(targets[0] if targets else ".")
    try:
        return install(base, dry_run=dry)
    except Exception as exc:
        print("ERROR:", exc, file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
